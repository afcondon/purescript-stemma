// Embeds the bundled examples in the page, at build time.
//
// For each example it copies the DOT text into a generated PureScript
// module (src/Site/Corpus.purs), and asks the installed Graphviz for its
// own drawing (public/graphviz/<name>.svg), so that the page can show the
// two side by side. The browser has no Graphviz, which is why this has to
// happen here and not in the page.
//
// Run from anywhere: node site/scripts/bundle-examples.mjs

import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repository = resolve(site, "..");

// The examples, in the order the picker shows them. `group` must name a
// constructor of Site.Example.Group.
const examples = [
  { group: "GraphvizGallery", file: "corpus/graphviz/clust4.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/unix.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/fsm.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/world.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/clust.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/clust5.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/process.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/states.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/KW91.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/alf.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/dfa.gv" },
  { group: "GraphvizGallery", file: "corpus/graphviz/crazy.gv" },
  { group: "Clusters", file: "corpus/clusters/three-deep.gv" },
  { group: "Clusters", file: "corpus/clusters/two-clusters-in-a-cycle.gv" },
  { group: "Clusters", file: "corpus/clusters/edge-into-a-cluster.gv" },
  { group: "RankSets", file: "corpus/ranksets/same-two-chains.gv" },
  { group: "RankSets", file: "corpus/ranksets/min-and-max.gv" },
  { group: "RankSets", file: "corpus/ranksets/sink-pushes-down.gv" },
];

// `dot -V` writes to standard error: "dot - graphviz version 14.1.2 (0)".
const versionLine = spawnSync("dot", ["-V"], { encoding: "utf8" }).stderr.trim();
const versionMatch = /version\s+(\S+)/.exec(versionLine);
if (!versionMatch) throw new Error(`could not read the Graphviz version from: ${versionLine}`);
const version = versionMatch[1];

const pictures = join(site, "public", "graphviz");
mkdirSync(pictures, { recursive: true });

// A PureScript string literal. PureScript accepts UTF-8 in source, so only
// the backslash, the quote and control characters need escaping.
const literal = (written) =>
  '"' +
  [...written]
    .map((character) => {
      if (character === "\\") return "\\\\";
      if (character === '"') return '\\"';
      if (character === "\n") return "\\n";
      if (character === "\t") return "\\t";
      if (character === "\r") return "\\r";
      const code = character.codePointAt(0);
      if (code < 0x20 || code === 0x7f) return "\\x" + code.toString(16).padStart(2, "0");
      return character;
    })
    .join("") +
  '"';

const entries = examples.map(({ group, file }) => {
  const name = file.split("/").pop().replace(/\.gv$/, "");
  const picture = `graphviz/${group.toLowerCase()}-${name}.svg`;
  execFileSync("dot", ["-Tsvg", join(repository, file), "-o", join(site, "public", picture)]);
  const dot = readFileSync(join(repository, file), "utf8");
  return [
    "  { name: ExampleName " + literal(name),
    "  , group: " + group,
    "  , source: " + literal(file),
    "  , graphvizPicture: " + literal(picture),
    "  , dot: " + literal(dot),
    "  }",
  ].join("\n");
});

const module = `-- | Generated by site/scripts/bundle-examples.mjs; do not edit by hand.
-- | Rerun that script to change the examples or after upgrading Graphviz.
module Site.Corpus (examples, graphvizVersion) where

import Site.Example (Example, ExampleName(..), Group(..))

-- | The version of Graphviz that drew the pictures in public/graphviz/.
graphvizVersion :: String
graphvizVersion = ${literal(version)}

examples :: Array Example
examples =
${entries.map((entry, index) => (index === 0 ? "  [ " : "  , ") + entry.trimStart().replace(/\n {2}/g, "\n    ")).join("\n")}
  ]
`;

writeFileSync(join(site, "src", "Site", "Corpus.purs"), module);
console.log(`${examples.length} examples bundled; pictures by Graphviz ${version}`);
